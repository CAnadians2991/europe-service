const nameOf = (c: CountryCode, lang: Lang) => {
  const x = COUNTRY[c] ?? COUNTRY_PRESETS.find((p) => p.code === c)
  return lang === 'uk' ? x?.name : x?.nameRu
}
const names = (codes: CountryCode[], lang: Lang) => codes.map((c) => nameOf(c, lang)).filter(Boolean).join(', ')
