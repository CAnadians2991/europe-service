export function CitySections({ code, lang, active }: { code: string; lang: 'uk' | 'ru'; active: Vacancy[] }) {
  const list = CITIES[code]
  if (!list) return null
  const uk = lang === 'uk'
  return (
    <section className="container-x space-y-8 pb-10" aria-label={uk ? 'Робота в містах' : 'Работа в городах'}>
      {list.map((c) => {
        const vs = active.filter((v) => v.country === code && c.re.test(`${v.city} ${v.hubCity ?? ''} ${v.title}`)).slice(0, 4)
        const t = c[lang]
        return (
          <div key={t.h} className="border-t border-line pt-6">
            <h2 className="text-[22px] sm:text-[28px]">{t.h}</h2>
            <p className="mt-2 max-w-3xl text-[15.5px] leading-relaxed text-ink-2">{t.text}</p>
            {vs.length > 0 && (
              <div className="mt-4 overflow-hidden rounded-[18px] border-x border-t border-line bg-white">
                {vs.map((v) => (
                  <VacancyCard key={v.id} v={toCard(localize(v, lang))} lang={lang} />
                ))}
              </div>
            )}
            <div className="mt-4 flex flex-wrap items-center gap-x-5 gap-y-2">
              <LeadButton form={`city-${code}`} title={t.h} submitLabel={uk ? 'Підібрати роботу' : 'Подобрать работу'} className="btn-accent !min-h-11 !px-5 !text-[15px]">
                {uk ? 'Підібрати роботу' : 'Подобрать работу'}
              </LeadButton>
              <Link href="#catalog" className="text-[14.5px] font-semibold text-brand-700 underline decoration-brand-300 underline-offset-[3px]">
                {uk ? 'Усі вакансії країни ↑' : 'Все вакансии страны ↑'}
              </Link>
            </div>
          </div>
        )
      })}
    </section>
  )
}
